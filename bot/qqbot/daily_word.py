def get_daily_word(date: datetime.date = None) -> str:
    """按日期稳定选取一条箴言（同日恒定）。"""
    d = date or datetime.date.today()
    idx = d.toordinal() % len(_DAILY_WORDS)
    return _DAILY_WORDS[idx]


def format_daily_word(date: datetime.date = None) -> str:
    """播报用的每日一言文案块。"""
    return "📜 每日一言：\n" + get_daily_word(date)
